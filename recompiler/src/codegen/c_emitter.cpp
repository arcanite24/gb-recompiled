void CEmitter::emit_halt(uint16_t next_pc) {
    emit_indent();
    out_ << "if (!ctx->ime && (gbrt_read8(ctx, 0xFFFF) & gbrt_read8(ctx, 0xFF0F) & 0x1F)) {\n";
    indent_level_++;
    emit_indent();
    out_ << "ctx->halt_bug = 1;\n";
    emit_indent();
    out_ << "ctx->pc = 0x" << std::hex << next_pc << std::dec << ";\n";
    emit_indent();
    out_ << "return;\n";
    indent_level_--;
    emit_indent();
    out_ << "} else {\n";
    indent_level_++;
    emit_line("gbrt_halt(ctx);");
    indent_level_--;
    emit_indent();
    out_ << "}\n";
}
